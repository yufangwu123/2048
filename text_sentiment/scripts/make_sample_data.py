def augment(text: str, rng: random.Random) -> str:
    extras_pos = ["真的", "确实", "整体来说", "个人觉得", "强烈"]
    extras_neg = ["说实话", "很遗憾", "总之", "坦白讲", "感觉"]
    if "推荐" in text or "好" in text or "棒" in text or "赞" in text:
        prefix = rng.choice(extras_pos)
    else:
        prefix = rng.choice(extras_neg)
    if rng.random() < 0.5:
        return f"{prefix}，{text}"
    return text


def build_rows(seed: int = 42) -> List[Tuple[str, int]]:
    rng = random.Random(seed)
    rows = []  # type: List[Tuple[str, int]]
    for text in POSITIVE:
        rows.append((text, 1))
        rows.append((augment(text, rng), 1))
    for text in NEGATIVE:
        rows.append((text, 0))
        rows.append((augment(text, rng), 0))
    rng.shuffle(rows)
    return rows


def write_csv(path: Path, rows: List[Tuple[str, int]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["text", "label"])
        writer.writerows(rows)


def main() -> None:
    rows = build_rows()
    split = int(len(rows) * 0.8)
    train_rows, val_rows = rows[:split], rows[split:]
    write_csv(OUT_DIR / "train.csv", train_rows)
    write_csv(OUT_DIR / "val.csv", val_rows)
    print(f"wrote {len(train_rows)} train + {len(val_rows)} val -> {OUT_DIR}")


if __name__ == "__main__":
    main()
